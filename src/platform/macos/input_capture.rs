/// Requests the normal macOS Accessibility prompt; never bypasses TCC.
pub fn check_permission() -> io::Result<()> {
    // SAFETY: the dictionary uses immortal system constants and null callbacks,
    // so their lifetime exceeds its lifetime. Each owned CF value is released.
    let trusted = unsafe {
        let options = CFDictionaryCreateMutable(ptr::null(), 1, ptr::null(), ptr::null());
        if options.is_null() {
            return Err(io::Error::other("could not allocate Accessibility options"));
        }
        CFDictionarySetValue(options, kAXTrustedCheckOptionPrompt, kCFBooleanTrue);
        let trusted = AXIsProcessTrustedWithOptions(options) != 0;
        CFRelease(options);
        trusted
    };
    if !trusted {
        let executable = std::env::current_exe()
            .map(|path| path.display().to_string())
            .unwrap_or_else(|_| "无法读取当前程序路径".into());
        return Err(io::Error::new(
            io::ErrorKind::PermissionDenied,
            format!(
                "macOS 尚未授权当前运行的程序使用辅助功能。当前执行文件：{executable}\n\
                 请完全退出程序，在系统设置 → 隐私与安全性 → 辅助功能中授权本次运行的应用。\
                 如果 Personal Device Link 已勾选但仍提示，可能是更新后的程序与旧授权记录不匹配：\
                 移除旧条目，重新添加本次构建的 .app、开启权限，再启动同一份应用。\
                 若运行的是 CLI，则检查实际启动它的终端应用权限。\
                 仅连接设备和传输文件不需要辅助功能权限。"
            ),
        ));
    }
    Ok(())
}

struct Context {
    options: ControlOptions,
    keyboard: MacKeyboard,
    pointer: MacPointer,
    queue: Arc<InputQueue>,
    running: Arc<AtomicBool>,
    failed: Arc<AtomicBool>,
    cursor: Option<Cursor>,
    local_pointer_allowed: bool,
    local_pointer: bool,
    buttons: BTreeSet<Button>,
}

unsafe extern "C" fn callback(
    _: *mut c_void,
    kind: u32,
    event: EventRef,
    user: *mut c_void,
) -> EventRef {
    // SAFETY: Capture owns the boxed Context until its tap is disabled and
    // invalidated. Callback executes synchronously on that thread's run loop.
    let context = unsafe { &mut *user.cast::<Context>() };
    if kind == u32::MAX - 1 || kind == u32::MAX {
        context.failed.store(true, Ordering::Release);
        context.running.store(false, Ordering::Release);
        return event;
    }
    if event.is_null() || !context.running.load(Ordering::Acquire) {
        return event;
    }
    // Never recapture events generated by our receiver.
    if unsafe { CGEventGetIntegerValueField(event, 42) } == INJECTED_TAG {
        return event;
    }
    // SAFETY: CoreGraphics supplies a live event for these keyboard event types.
    let code = unsafe { CGEventGetIntegerValueField(event, 9) } as u16;
    let flags = unsafe { CGEventGetFlags(event) };
    if kind == 10 && emergency_exit(code, flags, true) {
        context.running.store(false, Ordering::Release);
        return ptr::null_mut(); // Escape must never reach the remote machine.
    }
    let local = local_pointer_mode(
        context.local_pointer_allowed && context.options.pointer,
        context.local_pointer,
        flags,
        context.local_pointer
            && (0..3).any(|button| unsafe { CGEventSourceButtonState(0, button) }),
        matches!(kind, 2 | 4 | 26),
    );
    if local != context.local_pointer {
        context.local_pointer = local;
        if local {
            drop(context.cursor.take());
            for button in std::mem::take(&mut context.buttons) {
                if context
                    .queue
                    .push(InputEvent::Pointer(PointerEvent::Button {
                        button,
                        pressed: false,
                    }))
                    .is_err()
                {
                    context.failed.store(true, Ordering::Release);
                    context.running.store(false, Ordering::Release);
                }
            }
        } else {
            match Cursor::acquire() {
                Ok(cursor) => context.cursor = Some(cursor),
                Err(_) => {
                    context.failed.store(true, Ordering::Release);
                    context.running.store(false, Ordering::Release);
                }
            }
        }
    }
    // GUI mode reserves this physical chord for temporarily using the local
    // pointer, including the Stop Control button. No local clicks are forwarded.
    if context.local_pointer && !matches!(kind, 10..=12) {
        // Keep Control-click from becoming a local context menu over Stop.
        unsafe {
            CGEventSetFlags(event, flags & !(CONTROL_FLAG | OPTION_FLAG));
        }
        return event;
    }
    if (matches!(kind, 10..=12) && !context.options.keyboard)
        || (!matches!(kind, 10..=12) && !context.options.pointer)
    {
        return event;
    }
    let input = match kind {
        10 => Ok(context
            .keyboard
            .event(
                code,
                true,
                unsafe { CGEventGetIntegerValueField(event, 8) } != 0,
            )
            .map(InputEvent::Key)),
        11 => Ok(context
            .keyboard
            .event(code, false, false)
            .map(InputEvent::Key)),
        12 => Ok(context
            .keyboard
            .flags_changed(code, flags)
            .map(InputEvent::Key)),
        // moved, left/right/other dragged; use deltas even at screen edges.
        5 | 6 | 7 | 27 => {
            MacPointer::movement(unsafe { CGEventGetIntegerValueField(event, 4) }, unsafe {
                CGEventGetIntegerValueField(event, 5)
            })
            .map(|event| event.map(InputEvent::Pointer))
        }
        1 | 2 | 3 | 4 | 25 | 26 => {
            let button = match kind {
                1 | 2 => Some(Button::Left),
                3 | 4 => Some(Button::Right),
                _ if unsafe { CGEventGetIntegerValueField(event, 3) } == 2 => Some(Button::Middle),
                _ => None,
            };
            Ok(button.map(|button| {
                InputEvent::Pointer(PointerEvent::Button {
                    button,
                    pressed: matches!(kind, 1 | 3 | 25),
                })
            }))
        }
        22 => {
            // Continuous trackpads use pixel deltas (96/97). For discrete wheels,
            // CoreGraphics converts 16.16 fixed-point fields (93/94) to doubles.
            let continuous = unsafe { CGEventGetIntegerValueField(event, 88) } != 0;
            let (horizontal, vertical) = if continuous {
                (
                    unsafe { CGEventGetIntegerValueField(event, 97) } as f64,
                    unsafe { CGEventGetIntegerValueField(event, 96) } as f64,
                )
            } else {
                (unsafe { CGEventGetDoubleValueField(event, 94) }, unsafe {
                    CGEventGetDoubleValueField(event, 93)
                })
            };
            context
                .pointer
                .scroll(horizontal, vertical, continuous)
                .map(|event| event.map(InputEvent::Pointer))
        }
        _ => return event,
    };
    if let Ok(Some(InputEvent::Pointer(PointerEvent::Button { button, pressed }))) = input {
        if pressed {
            context.buttons.insert(button);
        } else {
            context.buttons.remove(&button);
        }
    }
    // Only a short queue lock here; never network I/O or waiting for queue space.
    if input
        .and_then(|input| match input {
            Some(input) => context.queue.push(input),
            None => Ok(()),
        })
        .is_err()
    {
        context.failed.store(true, Ordering::Release);
        context.running.store(false, Ordering::Release);
    }
    // All subscribed keyboard/pointer events stay remote while control is active.
    ptr::null_mut()
}

/// Balanced cursor ownership, including every early error path after acquisition.
struct Cursor;
impl Cursor {
    fn acquire() -> io::Result<Self> {
        // SAFETY: scalar CoreGraphics APIs, boolean_t is a 32-bit integer.
        let error = unsafe { CGAssociateMouseAndMouseCursorPosition(0) };
        if error != 0 {
            return Err(io::Error::other(format!(
                "Cannot capture pointer ({error}); keep the Mac terminal in the foreground"
            )));
        }
        let error = unsafe { CGDisplayHideCursor(0) };
        if error != 0 {
            unsafe {
                CGAssociateMouseAndMouseCursorPosition(1);
            }
            return Err(io::Error::other(format!(
                "Cannot hide local cursor ({error})"
            )));
        }
        Ok(Self)
    }
}
impl Drop for Cursor {
    fn drop(&mut self) {
        // SAFETY: balances the successful calls in acquire, exactly once.
        unsafe {
            let associate = CGAssociateMouseAndMouseCursorPosition(1);
            let show = CGDisplayShowCursor(0);
            if associate != 0 || show != 0 {
                eprintln!("Could not fully restore Mac cursor: association={associate}, visibility={show}");
            }
        }
    }
}

struct Tap {
    tap: *mut c_void,
    source: *mut c_void,
    run_loop: CFRef,
}
impl Drop for Tap {
    fn drop(&mut self) {
        // SAFETY: these owned CF objects are valid until their final release;
        // disabling and removing the source prevents callbacks after Context dies.
        unsafe {
            CGEventTapEnable(self.tap, false);
            CFRunLoopRemoveSource(self.run_loop, self.source, kCFRunLoopDefaultMode);
            CFMachPortInvalidate(self.tap);
            CFRelease(self.source);
            CFRelease(self.tap);
        }
    }
}

/// Owns the event tap on the main thread. Drop disables callbacks before freeing context.
pub struct Capture {
    _tap: Tap,
    context: Box<Context>,
}
impl Capture {
    pub fn is_running(&self) -> bool {
        self.context.running.load(Ordering::Acquire)
    }
    pub fn start(
        queue: Arc<InputQueue>,
        running: Arc<AtomicBool>,
        local_pointer_allowed: bool,
    ) -> io::Result<Self> {
        Self::start_with_config(
            queue,
            running,
            local_pointer_allowed,
            CaptureConfig {
                options: ControlOptions::ALL,
                target_os: "windows".into(),
            },
        )
    }
    pub fn start_with_config(
        queue: Arc<InputQueue>,
        running: Arc<AtomicBool>,
        local_pointer_allowed: bool,
        config: CaptureConfig,
    ) -> io::Result<Self> {
        config.options.validate()?;
        // SAFETY: this query has no pointer arguments and reads session key flags.
        if unsafe { CGEventSourceFlagsState(0) } & MODIFIER_FLAGS != 0 {
            return Err(io::Error::other(
                "Release Shift, Control, Option and Command before starting control.",
            ));
        }
        if (0..3).any(|button| unsafe { CGEventSourceButtonState(0, button) }) {
            return Err(io::Error::other(
                "Release all Mac mouse buttons before starting control.",
            ));
        }
        let failed = Arc::new(AtomicBool::new(false));
        let mut context = Box::new(Context {
            options: config.options,
            keyboard: MacKeyboard::for_target(&config.target_os, config.options.shortcut_mapping),
            pointer: MacPointer::default(),
            queue,
            running: Arc::clone(&running),
            failed: Arc::clone(&failed),
            cursor: None,
            local_pointer_allowed,
            local_pointer: false,
            buttons: BTreeSet::new(),
        });
        // kCGSessionEventTap=1, kCGHeadInsertEventTap=0, kCGEventTapOptionDefault=0.
        // SAFETY: Context remains alive through Tap::drop; callback signature matches
        // CGEventTapCallBack and only supported keyboard/pointer kinds are requested.
        let tap = unsafe {
            CGEventTapCreate(
                1,
                0,
                0,
                (1 << 1)
                    | (1 << 2)
                    | (1 << 3)
                    | (1 << 4)
                    | (1 << 5)
                    | (1 << 6)
                    | (1 << 7)
                    | (1 << 10)
                    | (1 << 11)
                    | (1 << 12)
                    | (1 << 22)
                    | (1 << 25)
                    | (1 << 26)
                    | (1 << 27),
                callback,
                (context.as_mut() as *mut Context).cast(),
            )
        };
        if tap.is_null() {
            return Err(io::Error::new(io::ErrorKind::PermissionDenied,
            "CGEventTapCreate failed. Check Accessibility/Input Monitoring permissions and disable Secure Keyboard Entry in the terminal if enabled."));
        }
        // SAFETY: tap is the valid owned result of CGEventTapCreate.
        let source = unsafe { CFMachPortCreateRunLoopSource(ptr::null(), tap, 0) };
        if source.is_null() {
            unsafe {
                CFMachPortInvalidate(tap);
                CFRelease(tap);
            }
            return Err(io::Error::other(
                "could not create keyboard event run-loop source",
            ));
        }
        let run_loop = unsafe { CFRunLoopGetCurrent() };
        let tap_guard = Tap {
            tap,
            source,
            run_loop,
        };
        unsafe {
            CFRunLoopAddSource(run_loop, source, kCFRunLoopDefaultMode);
            CGEventTapEnable(tap, true);
        }
        if config.options.pointer {
            context.cursor = Some(Cursor::acquire()?);
        }
        Ok(Self {
            _tap: tap_guard,
            context,
        })
    }

    pub fn finish(self) -> io::Result<()> {
        if self.context.failed.load(Ordering::Acquire) {
            Err(io::Error::other("Input capture stopped: event tap disabled, invalid event or input queue unavailable. Remote keys/buttons are being released."))
        } else {
            Ok(())
        }
    }
}

/// CLI run loop. Tauri instead keeps Capture alive in its existing main loop.
pub fn run(queue: Arc<InputQueue>, running: Arc<AtomicBool>) -> io::Result<()> {
    run_with_config(
        queue,
        running,
        CaptureConfig {
            options: ControlOptions::ALL,
            target_os: "windows".into(),
        },
    )
}
pub fn run_with_config(
    queue: Arc<InputQueue>,
    running: Arc<AtomicBool>,
    config: CaptureConfig,
) -> io::Result<()> {
    let capture = Capture::start_with_config(queue, Arc::clone(&running), false, config)?;
    println!("Keyboard and pointer control active. Emergency stop: Control + Option + Esc.");
    while running.load(Ordering::Acquire) {
        unsafe {
            CFRunLoopRunInMode(kCFRunLoopDefaultMode, 0.05, 1);
        }
    }
    capture.finish()
}
